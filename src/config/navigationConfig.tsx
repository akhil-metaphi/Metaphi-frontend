/* ═══════════════════════════════════════════════════
   Route Matching Utility Functions
   ═══════════════════════════════════════════════════ */

export function checkRouteMatch(pathname: string, pattern: string | RegExp): boolean {
  if (typeof pattern === "string") {
    if (pattern.endsWith("/*")) {
      const prefix = pattern.slice(0, -2);
      return pathname === prefix || pathname.startsWith(prefix + "/");
    }
    if (pattern.endsWith("*")) {
      const prefix = pattern.slice(0, -1);
      return pathname.startsWith(prefix);
    }
    return pathname === pattern;
  }
  return pattern.test(pathname);
}

export function isSubItemActive(sub: NavSubItem, pathname: string): boolean {
  if (pathname === sub.path || pathname.startsWith(sub.path + "/")) {
    return true;
  }
  if (sub.matchPatterns && sub.matchPatterns.length > 0) {
    return sub.matchPatterns.some((pattern) => checkRouteMatch(pathname, pattern));
  }
  return false;
}

export function isNavItemActive(item: NavItem, pathname: string): boolean {
  if (item.path) {
    if (pathname === item.path || pathname.startsWith(item.path + "/")) {
      return true;
    }
    if (item.matchPatterns && item.matchPatterns.length > 0) {
      return item.matchPatterns.some((pattern) => checkRouteMatch(pathname, pattern));
    }
    return false;
  }
  if (item.submenu) {
    return item.submenu.some((sub) => isSubItemActive(sub, pathname));
  }
  return false;
}

export function getActiveParentTitle(pathname: string): string | null {
  for (const item of navigationItems) {
    if (item.submenu && isNavItemActive(item, pathname)) {
      return item.title;
    }
  }
  return null;
}
